-- Hjertekraft store foundation. This project is new and has no existing public tables.

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique check (char_length(trim(name)) between 1 and 80),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  description text not null default '',
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  category_id uuid references public.categories(id) on delete set null,
  name text not null check (char_length(trim(name)) between 1 and 140),
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  short_description text not null default '' check (char_length(short_description) <= 240),
  description text not null default '',
  price_ore integer not null check (price_ore >= 0),
  compare_at_price_ore integer check (compare_at_price_ore is null or compare_at_price_ore >= price_ore),
  images text[] not null default '{}',
  stock_quantity integer check (stock_quantity is null or stock_quantity >= 0),
  is_featured boolean not null default false,
  is_published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_name text not null,
  customer_email text not null,
  customer_phone text,
  shipping_address jsonb not null default '{}'::jsonb,
  currency text not null default 'NOK' check (currency = 'NOK'),
  subtotal_ore integer not null check (subtotal_ore >= 0),
  shipping_ore integer not null default 0 check (shipping_ore >= 0),
  total_ore integer not null check (total_ore = subtotal_ore + shipping_ore),
  payment_provider text check (payment_provider in ('stripe', 'vipps')),
  payment_status text not null default 'pending' check (payment_status in ('pending', 'paid', 'failed', 'refunded')),
  fulfillment_status text not null default 'new' check (fulfillment_status in ('new', 'processing', 'sent', 'completed', 'cancelled')),
  provider_reference text unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  unit_price_ore integer not null check (unit_price_ore >= 0),
  quantity integer not null check (quantity between 1 and 99),
  line_total_ore integer not null check (line_total_ore = unit_price_ore * quantity),
  created_at timestamptz not null default now()
);

create table if not exists public.contact_messages (
  id uuid primary key default gen_random_uuid(),
  name text not null check (char_length(trim(name)) between 1 and 120),
  email text not null check (char_length(email) <= 254 and email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
  phone text check (phone is null or char_length(phone) <= 40),
  message text not null check (char_length(trim(message)) between 10 and 3000),
  consent boolean not null check (consent),
  status text not null default 'new' check (status in ('new', 'read', 'replied', 'archived')),
  created_at timestamptz not null default now()
);

create index if not exists products_public_order_idx on public.products (is_published, created_at desc);
create index if not exists products_category_idx on public.products (category_id);
create index if not exists orders_fulfillment_idx on public.orders (fulfillment_status, created_at desc);
create index if not exists contact_messages_inbox_idx on public.contact_messages (status, created_at desc);
create index if not exists order_items_order_idx on public.order_items (order_id);
create index if not exists order_items_product_idx on public.order_items (product_id);

alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.contact_messages enable row level security;

drop policy if exists "Published categories are visible to visitors" on public.categories;
create policy "Published categories are visible to visitors"
  on public.categories for select to anon, authenticated using (true);
drop policy if exists "Store admins manage categories" on public.categories;
create policy "Store admins manage categories"
  on public.categories for insert to authenticated
  with check (((select auth.jwt()) -> 'app_metadata' ->> 'store_admin') = 'true');
drop policy if exists "Store admins update categories" on public.categories;
create policy "Store admins update categories"
  on public.categories for update to authenticated
  using (((select auth.jwt()) -> 'app_metadata' ->> 'store_admin') = 'true')
  with check (((select auth.jwt()) -> 'app_metadata' ->> 'store_admin') = 'true');
drop policy if exists "Store admins delete categories" on public.categories;
create policy "Store admins delete categories"
  on public.categories for delete to authenticated
  using (((select auth.jwt()) -> 'app_metadata' ->> 'store_admin') = 'true');

