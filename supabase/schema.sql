create policy "Visitors can send contact messages"
  on public.contact_messages for insert to anon
  with check (status = 'new');
drop policy if exists "Store admins read and manage contact messages" on public.contact_messages;
create policy "Store admins read and manage contact messages"
  on public.contact_messages for all to authenticated
  using (((select auth.jwt()) -> 'app_metadata' ->> 'store_admin') = 'true')
  with check (((select auth.jwt()) -> 'app_metadata' ->> 'store_admin') = 'true');

